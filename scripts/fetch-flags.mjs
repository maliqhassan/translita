/**
 * Downloads the flag images the app bundles, and writes the map that loads
 * them.
 *
 *   node scripts/fetch-flags.mjs
 *
 * Flags used to be the phone's own emoji, cropped to a circle. That cannot be
 * made to line up: every manufacturer's emoji font draws flags at a different
 * size, offset and shape (some waving, some padded), so no one crop fits them
 * all. Real images crop the same everywhere.
 *
 * The country for each language is decided in one place,
 * `src/constants/language-flags.ts`; this reads the codes from there, so the
 * two cannot drift. Images come from flagcdn.com, whose artwork is the public
 * domain flag set from Wikimedia Commons. They are committed and bundled:
 * nothing is fetched while the app runs, so flags show offline.
 */

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const MAPPING = 'src/constants/language-flags.ts';
const OUT_DIR = 'assets/flags';
const MAP_FILE = 'src/constants/flag-images.ts';
/** 160px wide: sharp at 3x for a round badge up to ~50pt across. */
const WIDTH = 160;

const regions = [
  ...new Set([...readFileSync(MAPPING, 'utf8').matchAll(/: '([A-Z]{2})',/g)].map((m) => m[1])),
].sort();

if (regions.length === 0) throw new Error(`No region codes found in ${MAPPING}`);

mkdirSync(OUT_DIR, { recursive: true });

for (const region of regions) {
  const code = region.toLowerCase();
  const response = await fetch(`https://flagcdn.com/w${WIDTH}/${code}.png`);
  if (!response.ok) throw new Error(`${region}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  // A PNG, not an error page that happened to return 200.
  if (bytes.subarray(1, 4).toString() !== 'PNG') throw new Error(`${region}: not a PNG`);
  writeFileSync(`${OUT_DIR}/${code}.png`, bytes);
}

const lines = regions.map(
  (region) => `  ${region}: require('../../${OUT_DIR}/${region.toLowerCase()}.png'),`,
);

writeFileSync(
  MAP_FILE,
  `/**
 * Bundled flag images, keyed by region code. Generated by
 * \`scripts/fetch-flags.mjs\` from the regions in \`language-flags.ts\` — edit
 * that file and re-run the script rather than editing this one.
 *
 * Kept out of the constants barrel on purpose: these are image requires, which
 * only the bundler understands, so anything that merely needs a region code
 * (including the tests) imports \`language-flags\` and never loads this.
 */
export const FLAG_IMAGES: Readonly<Record<string, number>> = {
${lines.join('\n')}
};
`,
);

console.log(`Downloaded ${regions.length} flags into ${OUT_DIR} and wrote ${MAP_FILE}.`);
